import { applyToInstances } from '@/lib/analysis/pipeline';
import { computeSavings } from '@/lib/analysis/pipeline';
import { calculateCost } from '@/lib/pricing/priceEngine';
import { exportOptimizedLDraw } from '@/lib/export/ldrawExport';
import { buildChangeLogCsv, buildJsonReport, buildWantedListXml } from '@/lib/export/reports';
import { getCatalog } from '@/lib/runtime/services';
import { loadAnalysis } from '@/lib/runtime/store';
import { rehydrate, resolveEnabledIds } from '@/lib/runtime/rehydrate';
import { sanitizeFilename } from '@/lib/security/limits';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

type ExportKind = 'ldraw' | 'report' | 'csv' | 'wanted-list' | 'wanted-list-original';

const KINDS: ReadonlySet<string> = new Set<ExportKind>([
  'ldraw',
  'report',
  'csv',
  'wanted-list',
  'wanted-list-original',
]);

export async function POST(
  request: Request,
  context: { params: Promise<{ id: string }> },
): Promise<Response> {
  const { id } = await context.params;
  const record = loadAnalysis(id);
  if (!record) {
    return new Response(JSON.stringify({ error: 'That analysis is no longer available.' }), {
      status: 404,
      headers: { 'content-type': 'application/json' },
    });
  }

  const url = new URL(request.url);
  const kind = url.searchParams.get('kind') ?? 'ldraw';
  if (!KINDS.has(kind)) {
    return new Response(JSON.stringify({ error: `Unknown export "${kind}".` }), {
      status: 400,
      headers: { 'content-type': 'application/json' },
    });
  }

  let body: { enabledIds?: unknown } = {};
  try {
    body = (await request.json()) as { enabledIds?: unknown };
  } catch {
    // No body means "use the defaults".
  }
  const requested = Array.isArray(body.enabledIds)
    ? body.enabledIds.filter((v): v is string => typeof v === 'string')
    : undefined;
  const enabled = resolveEnabledIds(record, requested);

  const { document, instances, prices } = rehydrate(record);
  const base = sanitizeFilename(record.result.model.fileName).replace(/\.(ldr|mpd)$/i, '') || 'model';

  if (kind === 'ldraw') {
    const exported = exportOptimizedLDraw({
      document,
      candidates: record.result.candidates,
      enabledIds: enabled,
      modelName: record.result.model.fileName,
      priceSourceLabel: record.result.pricing.isDemoData
        ? `${record.result.pricing.sourceLabel} (DEMO PRICE DATA)`
        : record.result.pricing.sourceLabel,
    });
    return download(exported.text, exported.fileName, 'text/plain; charset=utf-8');
  }

  // Two Wanted Lists, deliberately. Ours is a parts-price estimate; only
  // BrickLink knows what an order actually costs once sellers, shipping and
  // minimums are involved. Exporting both lets the user put each through
  // BrickLink's own purchasing tools and compare real totals - which is a far
  // better answer than any shipping estimate we could invent.
  if (kind === 'wanted-list' || kind === 'wanted-list-original') {
    const isOriginal = kind === 'wanted-list-original';
    // The ORIGINAL list is built from the untouched inventory. No candidate is
    // applied to it, whatever the user has enabled.
    const listInstances = isOriginal
      ? instances
      : applyToInstances(instances, record.result.candidates, enabled);
    const wanted = buildWantedListXml(listInstances, getCatalog(), record.result.pricing.condition);
    const which = isOriginal
      ? 'ORIGINAL inventory, exactly as the model was uploaded'
      : `OPTIMIZED inventory, with ${enabled.size} of ${record.result.candidates.length} proposed changes applied`;
    const header =
      `<!--\n` +
      `  BrickLink Wanted List generated by BrickThrift from ${escapeComment(record.result.model.fileName)}.\n` +
      `  ${which}.\n` +
      `  ${wanted.itemCount} lots, ${wanted.pieceCount} pieces.\n` +
      (wanted.excluded.length > 0
        ? `  ${wanted.excluded.length} lot(s) were EXCLUDED because their BrickLink part number or\n` +
          `  color could not be resolved with confidence. They are listed in the JSON report.\n` +
          `  Excluded: ${escapeComment(
            wanted.excluded
              .slice(0, 20)
              .map((e) => `${e.partId}/${e.colorId} x${e.quantity}`)
              .join(', '),
          )}\n`
        : '') +
      `  Import BOTH lists into BrickLink and compare the two order totals: that comparison,\n` +
      `  not our parts estimate, is what tells you whether the change saves money.\n` +
      `  This XML follows BrickLink's documented Wanted List format. Please check the first\n` +
      `  import: it has not been round-tripped through a live BrickLink account by this build.\n` +
      `-->\n`;
    return download(
      header + wanted.xml,
      `${base}-wanted-list-${isOriginal ? 'original' : 'optimized'}.xml`,
      'application/xml; charset=utf-8',
    );
  }

  if (kind === 'csv') {
    const csv = buildChangeLogCsv(record.result.candidates, enabled);
    return download(csv, `${base}-changes.csv`, 'text/csv; charset=utf-8');
  }

  const optimizedInstances = applyToInstances(instances, record.result.candidates, enabled);
  const optimizedCost = calculateCost(
    optimizedInstances,
    prices,
    record.result.pricing.condition,
    record.result.pricing.currency,
  );
  const savings = computeSavings(
    record.result.originalCost.total,
    optimizedCost.total,
    record.result.candidates,
    enabled,
    record.result.pricing.currency,
  );
  const report = buildJsonReport(record.result, savings, enabled);
  return download(
    JSON.stringify(report, null, 2),
    `${base}-optimization-report.json`,
    'application/json; charset=utf-8',
  );
}

function download(body: string, filename: string, contentType: string): Response {
  return new Response(body, {
    headers: {
      'content-type': contentType,
      'content-disposition': `attachment; filename="${filename.replace(/"/g, '')}"`,
      'cache-control': 'no-store',
    },
  });
}

function escapeComment(value: string): string {
  return value.replace(/--/g, '- -').replace(/[<>]/g, '');
}
