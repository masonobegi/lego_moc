/**
 * One physical part in the completed model.
 *
 * `commandRef` is the single most important field: it identifies the exact
 * line type 1 that produced this instance. Because a submodel may be referenced
 * more than once, several PartInstances can share one commandRef - editing that
 * line changes all of them. The optimizer groups candidates by commandRef for
 * exactly this reason (see src/lib/optimizer/candidates.ts).
 */
export interface PartInstance {
  /** Unique within a model. Encodes the full reference path, so it is stable across re-parses. */
  readonly instanceId: string;
  /** Normalized part id: lowercase, `.dat` stripped, `\` -> `/`. e.g. `3001`. */
  readonly partId: string;
  /** The reference exactly as written on the line. */
  readonly partFile: string;
  /** Effective color after resolving color 16 (inherit) up the reference chain. */
  readonly colorId: number;
  /** Color as written on this line, before inheritance resolution. */
  readonly declaredColorId: number;
  readonly position: Vec3;
  readonly transformation: Mat3;
  /** 0-based build step within `parentModel`. */
  readonly stepIndex: number;
  /** Name of the sub-file that contains the line. */
  readonly parentModel: string;
  /** Path of sub-file names from the root down to `parentModel`. */
  readonly modelPath: readonly string[];
  /** Nesting depth: 0 for a part referenced directly by the root model. */
  readonly depth: number;
  readonly commandRef: CommandRef;
}

/** Addresses one command inside one sub-file of a document. */
export interface CommandRef {
  /** Index into LDrawDocument.files. */
  readonly fileIndex: number;
  /** Index into ModelFile.commands. */
  readonly commandIndex: number;
}

export function commandRefKey(ref: CommandRef): string {
  return `${ref.fileIndex}:${ref.commandIndex}`;
}

export interface UnresolvedReference {
  /** Reference as written. */
  readonly file: string;
  /** Normalized id used for lookup. */
  readonly partId: string;
  /** Number of times it appears. */
  readonly count: number;
  readonly reason: 'not_in_document' | 'not_in_library';
}

export interface ResolvedModel {
  readonly document: LDrawDocument;
  readonly instances: PartInstance[];
  /** Submodel references that could not be resolved inside the document. */
  readonly unresolvedSubmodels: string[];
  /** Total number of build steps in the root model. */
  readonly rootStepCount: number;
  /** Number of distinct sub-files actually reachable from the root. */
  readonly submodelCount: number;
  readonly warnings: ParseWarning[];
  /** True when expansion hit a configured limit and the result is partial. */
  readonly truncated: boolean;
  readonly truncationReason: string | null;
}
